"""Tests for engine.py. These go green only when your gradients are correct.

    python -m pytest -x          stop at the first failure (recommended)
    python -m pytest -q          just the score
    python -m pytest -k relu     run one thing

They are ordered roughly the way you should implement: forward passes first,
then backward, then the composite behaviours that catch the classic bugs.
Do not edit this file to make it pass. That is the one way to waste the rung.
"""

import math

import pytest

from engine import Value

TOL = 1e-6


def close(a, b, tol=TOL):
    return abs(a - b) < tol


# ----------------------------------------------------------------------
# 1. Forward passes. No gradients yet - just "does it compute the number".
# ----------------------------------------------------------------------

def test_add_forward():
    assert close((Value(2.0) + Value(3.0)).data, 5.0)


def test_mul_forward():
    assert close((Value(2.0) * Value(3.0)).data, 6.0)


def test_scalar_operands():
    """Plain ints and floats should work on either side of the operator."""
    x = Value(4.0)
    assert close((x + 3).data, 7.0)
    assert close((3 + x).data, 7.0)
    assert close((x * 3).data, 12.0)
    assert close((3 * x).data, 12.0)


# ----------------------------------------------------------------------
# 2. Backward. Needs __add__, __mul__ and backward().
# ----------------------------------------------------------------------

def test_add_backward():
    """Addition is a pipe: gradient 1.0 reaches both inputs unchanged."""
    a, b = Value(2.0), Value(3.0)
    (a + b).backward()
    assert close(a.grad, 1.0), f"expected a.grad == 1.0, got {a.grad}"
    assert close(b.grad, 1.0), f"expected b.grad == 1.0, got {b.grad}"


def test_mul_backward():
    """Each input is scaled by the OTHER input's value."""
    a, b = Value(2.0), Value(3.0)
    (a * b).backward()
    assert close(a.grad, 3.0), f"expected a.grad == b.data == 3.0, got {a.grad}"
    assert close(b.grad, 2.0), f"expected b.grad == a.data == 2.0, got {b.grad}"


def test_backward_seeds_the_root():
    """d(x)/d(x) is 1. Without seeding the root, every gradient stays zero."""
    x = Value(5.0)
    y = x * 2
    y.backward()
    assert close(y.grad, 1.0), f"the node you call .backward() on needs grad 1.0, got {y.grad}"


def test_chain_of_two_ops():
    """d = (a * b) + c.  dd/da = b = 3,  dd/db = a = 2,  dd/dc = 1."""
    a, b, c = Value(2.0), Value(3.0), Value(10.0)
    d = a * b + c
    d.backward()
    assert close(d.data, 16.0)
    assert close(a.grad, 3.0), f"expected 3.0, got {a.grad}"
    assert close(b.grad, 2.0), f"expected 2.0, got {b.grad}"
    assert close(c.grad, 1.0), f"expected 1.0, got {c.grad}"


# ----------------------------------------------------------------------
# 3. The two bugs everybody writes at least once.
# ----------------------------------------------------------------------

def test_reuse_accumulates():
    """b = a * a.  db/da = 2a = 8, because gradient arrives from BOTH inputs.

    If you wrote `self.grad = ...` instead of `self.grad += ...`, one of the
    two contributions is overwritten and you get 4.0 here.
    """
    a = Value(4.0)
    b = a * a
    b.backward()
    assert close(a.grad, 8.0), (
        f"expected a.grad == 2*a == 8.0, got {a.grad}. "
        "If you got 4.0, you are assigning gradient instead of accumulating it."
    )


def test_two_paths_to_the_same_input():
    """`a` reaches `d` by two routes of different lengths, and both count.

        c = a*a + a          dc/da = 2a + 1 = 5
        d = c*c              dd/dc = 2c = 12
                             dd/da = 12 * 5 = 60
    """
    a = Value(2.0)
    c = a * a + a
    d = c * c
    d.backward()
    assert close(c.data, 6.0)
    assert close(d.data, 36.0)
    assert close(a.grad, 60.0), f"expected a.grad == 60.0, got {a.grad}"


def test_topological_order():
    """An intermediate node consumed three times, at two different depths.

        u = a*a              du/da = 2a  = 4
        v = u + u*u + a      dv/du = 1 + 2u = 9
                             dv/da = 9 * 4 + 1 = 37   (+1 for the direct path)

    `u` collects gradient from three consumers. If you call u._backward() as
    soon as you reach u - rather than waiting until every consumer has
    deposited into u.grad - you propagate a fraction of the real gradient and
    get 5.0 instead of 37.0.

    This is the test that fails if you walk the graph top-down and call
    _backward() as you go. Sort first, then sweep.
    """
    a = Value(2.0)
    u = a * a
    v = u + u * u + a
    v.backward()
    assert close(v.data, 22.0)
    assert close(a.grad, 37.0), (
        f"expected a.grad == 37.0, got {a.grad}. "
        "Build the full topological order first, then call _backward() in "
        "reverse - never during the walk."
    )


