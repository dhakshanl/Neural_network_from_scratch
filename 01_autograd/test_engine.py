def test_pow_forward_and_backward():
    """y = x**3.  dy/dx = 3x^2 = 27 at x = 3."""
    x = Value(3.0)
    y = x ** 3
    y.backward()
    assert close(y.data, 27.0)
    assert close(x.grad, 27.0), f"expected 3*x**2 == 27.0, got {x.grad}"


def test_negative_exponent():
    """y = x**-1 = 1/x.  dy/dx = -1/x^2 = -0.25 at x = 2."""
    x = Value(2.0)
    y = x ** -1
    y.backward()
    assert close(y.data, 0.5)
    assert close(x.grad, -0.25), f"expected -0.25, got {x.grad}"


def test_sub_and_div_come_free():
    """You never wrote a derivative for these. They still work."""
    a, b = Value(6.0), Value(3.0)
    c = a - b
    c.backward()
    assert close(c.data, 3.0)
    assert close(a.grad, 1.0)
    assert close(b.grad, -1.0), f"expected -1.0, got {b.grad}"

    a, b = Value(6.0), Value(3.0)
    c = a / b
    c.backward()
    assert close(c.data, 2.0)
    assert close(a.grad, 1 / 3), f"expected 1/b == 0.333..., got {a.grad}"
    assert close(b.grad, -6.0 / 9.0), f"expected -a/b**2 == -0.666..., got {b.grad}"


