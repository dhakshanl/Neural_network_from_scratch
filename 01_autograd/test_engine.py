def test_relu_positive():
    x = Value(3.0)
    y = x.relu()
    y.backward()
    assert close(y.data, 3.0)
    assert close(x.grad, 1.0), f"active unit should pass gradient through, got {x.grad}"


def test_relu_negative():
    x = Value(-3.0)
    y = x.relu()
    y.backward()
    assert close(y.data, 0.0), f"relu(-3) should be 0.0, got {y.data}"
    assert close(x.grad, 0.0), f"dead unit should block gradient, got {x.grad}"


def test_tanh():
    x = Value(0.7)
    y = x.tanh()
    y.backward()
    assert close(y.data, math.tanh(0.7))
    assert close(x.grad, 1 - math.tanh(0.7) ** 2), (
        f"expected 1 - tanh(x)**2 == {1 - math.tanh(0.7) ** 2:.6f}, got {x.grad}"
    )


# ----------------------------------------------------------------------
# 6. The real check: every gradient against finite differences.
#
#    dL/dx  ~  (L(x + eps) - L(x - eps)) / (2 * eps)
#
#    Slow, dumb, and impossible to get wrong - which is exactly why it is the
#    reference. You will use this same trick on every project from here on.
# ----------------------------------------------------------------------

def numeric_grad(f, inputs, i, eps=1e-6):
    """Wiggle input i, see how much f moves. Uses only the forward pass."""
    original = inputs[i].data

    inputs[i].data = original + eps
    high = f(inputs).data
    inputs[i].data = original - eps
    low = f(inputs).data
    inputs[i].data = original

    return (high - low) / (2 * eps)


EXPRESSIONS = [
    ("a*b + c",            lambda v: v[0] * v[1] + v[2]),
    ("(a+b) * (b+c)",      lambda v: (v[0] + v[1]) * (v[1] + v[2])),
    ("a*a*a - b/c",        lambda v: v[0] * v[0] * v[0] - v[1] / v[2]),
    ("tanh(a*b + c)",      lambda v: (v[0] * v[1] + v[2]).tanh()),
    ("relu(a - b) * c",    lambda v: (v[0] - v[1]).relu() * v[2]),
    ("(a*b + c**2).tanh() * a", lambda v: (v[0] * v[1] + v[2] ** 2).tanh() * v[0]),
    ("2/a + 3*b - c",      lambda v: 2 / v[0] + 3 * v[1] - v[2]),
]


@pytest.mark.parametrize("name,f", EXPRESSIONS, ids=[e[0] for e in EXPRESSIONS])
def test_matches_finite_differences(name, f):
    values = [Value(1.7), Value(-0.4), Value(2.3)]

    out = f(values)
    out.backward()
    analytic = [v.grad for v in values]

    for i, letter in enumerate("abc"):
        expected = numeric_grad(f, values, i)
        assert close(analytic[i], expected, tol=1e-4), (
            f"{name}: d/d{letter} was {analytic[i]:.6f}, "
            f"finite differences say {expected:.6f}"
        )
